#!/usr/bin/env node

/**
 * Bundles the legal documents in /content into a TS module so the app can
 * render them without network access or an auth session.
 *
 * Run after editing content/privacy-policy.md or content/terms-of-service.md:
 *   npm run legal:generate
 */

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const outputPath = path.join(root, "src/constants/Legal.ts");

const documents = {
  PrivacyPolicyMarkdown: "content/privacy-policy.md",
  TermsOfServiceMarkdown: "content/terms-of-service.md",
};

const constants = Object.entries(documents).map(([name, file]) => {
  const markdown = fs.readFileSync(path.join(root, file), "utf8");
  return `export const ${name} = ${JSON.stringify(markdown)};`;
});

const output = `// AUTO-GENERATED by scripts/generate-legal-content.js — do not edit by hand.
// Edit the files in /content and run \`npm run legal:generate\` instead.

${constants.join("\n\n")}
`;

fs.writeFileSync(outputPath, output);
console.log(`✅ Wrote ${path.relative(root, outputPath)}`);
